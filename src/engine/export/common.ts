import { type ColorFormat, formatColor, formatOklch, toHex } from '../color'
import { ALL_TOKENS } from '../tokens'
import { type Oklch, type PaletteResult, type ScaleKey, STEPS } from '../types'

export interface ExportOptions {
  format: ColorFormat
  /** P3 only: emit sRGB hex first, then oklch() inside @media (color-gamut: p3). */
  hexFallback: boolean
}

export const SCALE_ORDER: ScaleKey[] = [
  'primary',
  'secondary',
  'accent',
  'extra',
  'neutral',
  'success',
  'warning',
  'destructive',
  'info',
]

export function scaleEntries(result: PaletteResult): [ScaleKey, Oklch[]][] {
  return SCALE_ORDER.filter((k) => result.scales[k]).map((k) => [k, STEPS.map((s) => result.scales[k]![s])])
}

export function tokenEntries(result: PaletteResult, theme: 'light' | 'dark'): [string, Oklch][] {
  return ALL_TOKENS.filter((t) => result.tokens[theme][t]).map((t) => [t, result.tokens[theme][t]])
}

export function value(c: Oklch, opts: ExportOptions): string {
  return formatColor(c, opts.format)
}

export function wantsHexFallback(result: PaletteResult, opts: ExportOptions) {
  return result.config.gamut === 'p3' && opts.hexFallback && opts.format === 'oklch'
}

export const header = (result: PaletteResult) =>
  `/* Generated by 23palette — seed #${result.config.seed}, ${result.config.harmony}. Score ${result.audit.score}/100. */`

export { formatOklch, toHex }
